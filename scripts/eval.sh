#!/usr/bin/env bash
# scripts/eval.sh — eval subcommand worker for Conjure.
# Subcommands: init (EVAL-01), run (EVAL-02), --emit-workflow (Wave 2 stub).
# Invoked via cli/conjure eval, or directly: bash eval.sh <subcmd> [target].
#
# Dispatch: reads CONJURE_EVAL_CMD env var (set by cli/conjure); falls back to $1
# for direct invocation (test harness passes subcmd as first positional arg).
#
# POSIX bash 3.2+ compatible. No associative arrays, no mapfile, no local -n.
# All exits use exit 2 (never exit 1). backup-before-mutate via lib/mutate.sh.

set -uo pipefail

CONJURE_HOME="${CONJURE_HOME:-$(cd "$(dirname "$0")/.." && pwd)}"

PROMPTFOO_VERSION="0.121.14"
PROMPTFOO_NODE_MIN_MAJOR=20
PROMPTFOO_NODE_MIN_MINOR=20
FAIL_ON_THRESHOLD=80  # integer 80 = 0.8 fractional (action input is 0-100)

# Source lib/mutate.sh for mutate_mkdir, mutate_write_file
DRY_RUN="${DRY_RUN:-0}"
# shellcheck source=../lib/mutate.sh
. "$CONJURE_HOME/lib/mutate.sh"

# ──────────────────────────────────────────────────────────────────────────────
# _eval_check_node — POSIX bash 3.2+ node version preflight (Pattern 6)
# ──────────────────────────────────────────────────────────────────────────────
_eval_check_node() {
  if ! command -v node >/dev/null 2>&1; then
    echo "✗ conjure eval requires Node.js >=20.20.0 (not found)" >&2
    echo "  Install: https://nodejs.org" >&2
    exit 2
  fi
  _node_ver="$(node --version 2>/dev/null | tr -d 'v')"
  _node_major="${_node_ver%%.*}"
  _node_rest="${_node_ver#*.}"
  _node_minor="${_node_rest%%.*}"
  if [ "${_node_major:-0}" -lt "$PROMPTFOO_NODE_MIN_MAJOR" ] || \
     { [ "${_node_major:-0}" -eq "$PROMPTFOO_NODE_MIN_MAJOR" ] && \
       [ "${_node_minor:-0}" -lt "$PROMPTFOO_NODE_MIN_MINOR" ]; }; then
    echo "✗ conjure eval requires Node.js >=${PROMPTFOO_NODE_MIN_MAJOR}.${PROMPTFOO_NODE_MIN_MINOR}.0 (found: v${_node_ver})" >&2
    echo "  Upgrade Node.js: https://nodejs.org" >&2
    exit 2
  fi
}

# ──────────────────────────────────────────────────────────────────────────────
# _extract_rule_lines <claude_md_path>
# Extracts imperative/bullet content lines from CLAUDE.md (Pattern 7 / Code Examples).
# Excludes: headings (#), table rows (|), horizontal rules (--- ===), code fences (`),
# blockquotes (>), blank lines.
# ──────────────────────────────────────────────────────────────────────────────
_extract_rule_lines() {
  local claude_md="$1"
  grep -v '^[[:space:]]*#' "$claude_md" \
    | grep -v '^[[:space:]]*|' \
    | grep -v '^[[:space:]]*---' \
    | grep -v '^[[:space:]]*===' \
    | grep -v '^[[:space:]]*\`\`\`' \
    | grep -v '^[[:space:]]*>' \
    | grep -v '^[[:space:]]*$' \
    | grep -v '^[[:space:]]*@' \
    | sed 's/^[[:space:]]*//' \
    | grep -v '^$'
}

# ──────────────────────────────────────────────────────────────────────────────
# _list_installed_skills <target_dir>
# Discovers installed skill directory names via find against target_dir/.claude/skills.
# Uses the target-arg form — no cwd drift (plan constraint: absolute via $target_dir).
# ──────────────────────────────────────────────────────────────────────────────
_list_installed_skills() {
  local target_dir="$1"
  find "$target_dir/.claude/skills" -name SKILL.md 2>/dev/null \
    | sed "s|$target_dir/.claude/skills/||;s|/SKILL.md\$||" \
    | sort
}

# ──────────────────────────────────────────────────────────────────────────────
# _yaml_escape_single <string>
# Escapes a string for use in a single-quoted YAML scalar.
# Replaces every ' with '\''.
# ──────────────────────────────────────────────────────────────────────────────
_yaml_escape_single() {
  printf '%s' "$1" | sed "s/'/'\\\\''/g"
}

# ──────────────────────────────────────────────────────────────────────────────
# _validate_skill_name <name>
# Validates skill name matches [a-zA-Z0-9_-]+. Prints name if valid; exits warn if not.
# Returns 0 if valid, 1 if invalid (warn + skip).
# ──────────────────────────────────────────────────────────────────────────────
_validate_skill_name() {
  local name="$1"
  case "$name" in
    *[!a-zA-Z0-9_-]*)
      echo "warn: skill name '$name' contains unsafe chars — skipping (T-28-02)" >&2
      return 1
      ;;
  esac
  return 0
}

# ──────────────────────────────────────────────────────────────────────────────
# _build_promptfooconfig <target_dir> <output_tempfile>
# Builds the full promptfooconfig.yaml into a tempfile using printf line-by-line.
# Never uses a large heredoc with variable expansion (Pitfall 3 / T-28-01).
# ──────────────────────────────────────────────────────────────────────────────
_build_promptfooconfig() {
  local target_dir="$1"
  local outfile="$2"

  # Header comment + description
  printf '%s\n' \
    "# Generated by conjure eval init — do not edit manually" \
    "# Source: https://www.promptfoo.dev/docs/configuration/reference/" \
    "" \
    "description: 'Conjure harness prompt-adherence eval'" \
    "" \
    "providers:" \
    "  - id: anthropic:claude-agent-sdk" \
    "    config:" \
    "      working_dir: ." \
    "      setting_sources: ['project']" \
    "      skills: all" \
    "      permission_mode: dontAsk" \
    "      append_allowed_tools: ['Read', 'Bash']" \
    "" \
    "evaluateOptions:" \
    "  repeat: 3" \
    "" \
    "# Prompt: a minimal task that exercises the harness; repeated for each test" \
    "prompts:" \
    "  - 'Summarize the purpose of this project in one sentence.'" \
    "" \
    "defaultTest:" \
    "  options:" \
    "    disableVarExpansion: true" \
    "" \
    "tests:" \
    "  # EVAL-01 skill-used: one block per installed skill" \
    "  # (skill-used is deterministic; no per-assertion repeat needed)" \
    > "$outfile"

  # skill-used assertions (one per installed skill)
  local skill
  while IFS= read -r skill; do
    [ -z "$skill" ] && continue
    _validate_skill_name "$skill" || continue
    local escaped_skill
    escaped_skill="$(_yaml_escape_single "$skill")"
    printf '%s\n' \
      "  - description: 'skill routing: ${escaped_skill}'" \
      "    assert:" \
      "      - type: skill-used" \
      "        value: '${escaped_skill}'" \
      "" \
      >> "$outfile"
  done <<SKILLS_EOF
$(_list_installed_skills "$target_dir")
SKILLS_EOF

  # llm-rubric section header
  printf '%s\n' \
    "  # EVAL-01 llm-rubric: one block per CLAUDE.md rule line" \
    "  # (repeat:3 at evaluateOptions level provides the flakiness guard" \
    "  #  when combined with repeat-min-pass:2 in the GitHub Action)" \
    >> "$outfile"

  # llm-rubric assertions (one per CLAUDE.md rule line)
  if [ -f "$target_dir/CLAUDE.md" ]; then
    local rule_line
    while IFS= read -r rule_line; do
      [ -z "$rule_line" ] && continue
      local escaped_rule
      escaped_rule="$(_yaml_escape_single "$rule_line")"
      # Truncate description to 60 chars max
      local desc_text
      desc_text="$(printf '%s' "$rule_line" | cut -c1-60)"
      local escaped_desc
      escaped_desc="$(_yaml_escape_single "$desc_text")"
      printf '%s\n' \
        "  - description: 'rule: ${escaped_desc}'" \
        "    assert:" \
        "      - type: llm-rubric" \
        "        value: '${escaped_rule}'" \
        "        threshold: 0.8" \
        "" \
        >> "$outfile"
    done <<RULES_EOF
$(_extract_rule_lines "$target_dir/CLAUDE.md")
RULES_EOF
  fi
}

# ──────────────────────────────────────────────────────────────────────────────
# cmd_eval_init <target_dir>
# EVAL-01: scaffold .conjure/eval/promptfooconfig.yaml
# ──────────────────────────────────────────────────────────────────────────────
cmd_eval_init() {
  local target_dir="$1"

  # Resolve absolute path
  if [ ! -d "$target_dir" ]; then
    echo "✗ conjure eval init: target directory not found: $target_dir" >&2
    exit 2
  fi

  local eval_dir="$target_dir/.conjure/eval"
  mutate_mkdir "$eval_dir"

  # Build into a tempfile (Pitfall 6: mutate_write_file for byte-exact copy)
  local tmpfile
  tmpfile="$(mktemp)"
  _build_promptfooconfig "$target_dir" "$tmpfile"

  mutate_write_file "$eval_dir/promptfooconfig.yaml" "$tmpfile"
  rm -f "$tmpfile"

  echo "▸ conjure eval init: wrote .conjure/eval/promptfooconfig.yaml"
  echo "  Verify: review the generated config and run: conjure eval run"
}

# ──────────────────────────────────────────────────────────────────────────────
# cmd_eval_run <target_dir>
# EVAL-02: Node preflight + npx --yes promptfoo@PROMPTFOO_VERSION eval with exit passthrough
# ──────────────────────────────────────────────────────────────────────────────
cmd_eval_run() {
  local target_dir="$1"

  # Node version preflight (EVAL-02)
  _eval_check_node

  # npx availability check
  if ! command -v npx >/dev/null 2>&1; then
    echo "✗ conjure eval run: npx not found — install Node.js >=20.20.0" >&2
    echo "  Install: https://nodejs.org" >&2
    exit 2
  fi

  # Config existence check
  local config_file="$target_dir/.conjure/eval/promptfooconfig.yaml"
  if [ ! -f "$config_file" ]; then
    echo "✗ conjure eval run: no eval config found at $config_file" >&2
    echo "  Run: conjure eval init [target] first" >&2
    exit 2
  fi

  # ANTHROPIC_API_KEY advisory (warn only — do not exit; may be set in env)
  if [ -z "${ANTHROPIC_API_KEY:-}" ]; then
    echo "warn: ANTHROPIC_API_KEY not set — set it for LLM-graded assertions" >&2
  fi

  # Shell out with exit passthrough (never pipe — Pitfall: pipe loses exit code)
  npx --yes "promptfoo@${PROMPTFOO_VERSION}" eval -c "$config_file"
  local _pf_exit=$?
  exit $_pf_exit
}

# ──────────────────────────────────────────────────────────────────────────────
# cmd_eval_emit_workflow <target_dir>
# EVAL-03: emit .github/workflows/conjure-eval.yml via mutate_write_file.
# Builds the workflow YAML line-by-line with printf (no heredoc variable
# expansion — Pitfall 3). Uses FAIL_ON_THRESHOLD integer (80 = 0.8 fractional
# per D-28-THRESH; Pitfall 9 reconciliation). ${{ }} expressions are
# single-quote-protected so bash does NOT expand them.
# ──────────────────────────────────────────────────────────────────────────────
cmd_eval_emit_workflow() {
  local target_dir="$1"

  # Resolve absolute path
  if [ ! -d "$target_dir" ]; then
    echo "✗ conjure eval --emit-workflow: target directory not found: $target_dir" >&2
    exit 2
  fi

  # Create .github/workflows/ directory (backup-before-mutate via mutate_mkdir)
  local wf_dir="$target_dir/.github/workflows"
  mutate_mkdir "$wf_dir"

  # Build workflow YAML into a tempfile (Pitfall 6: use mutate_write_file for
  # byte-exact copy to avoid trailing-newline strip from command substitution).
  # All ${{ ... }} GitHub Actions expressions are inside single-quoted strings
  # so bash does NOT expand them (Pitfall 3 / T-28-03b mitigation).
  local _wf_tmp
  _wf_tmp="$(mktemp)"

  # Header + name + trigger
  printf '%s\n' \
    '# Generated by conjure eval --emit-workflow — do not edit manually' \
    'name: Conjure Eval' \
    'on:' \
    '  pull_request:' \
    '    paths:' \
    "      - '.claude/**'" \
    "      - 'CLAUDE.md'" \
    '' \
    'jobs:' \
    '  eval:' \
    '    runs-on: ubuntu-latest' \
    '    permissions:' \
    '      contents: read' \
    '      pull-requests: write' \
    '    steps:' \
    '      - uses: actions/checkout@v4' \
    '' \
    '      - name: Cache promptfoo' \
    '        uses: actions/cache@v4' \
    '        with:' \
    '          path: ~/.cache/promptfoo' \
    '          key: ${{ runner.os }}-promptfoo-v1-${{ hashFiles('"'"'.conjure/eval/promptfooconfig.yaml'"'"') }}' \
    '          restore-keys: |' \
    '            ${{ runner.os }}-promptfoo-v1-' \
    '' \
    '      - name: Run conjure eval' \
    '        uses: promptfoo/promptfoo-action@v1' \
    '        with:' \
    '          github-token: ${{ secrets.GITHUB_TOKEN }}' \
    "          config: '.conjure/eval/promptfooconfig.yaml'" \
    "          promptfoo-version: '${PROMPTFOO_VERSION}'" \
    "          fail-on-threshold: ${FAIL_ON_THRESHOLD}" \
    '          repeat: 3' \
    '          repeat-min-pass: 2' \
    '          cache-path: ~/.cache/promptfoo' \
    '        env:' \
    '          ANTHROPIC_API_KEY: ${{ secrets.ANTHROPIC_API_KEY }}' \
    >> "$_wf_tmp"

  # Write to destination via mutate_write_file (byte-exact; preserves trailing newline)
  mutate_write_file "$wf_dir/conjure-eval.yml" "$_wf_tmp"
  rm -f "$_wf_tmp"

  echo "▸ conjure eval --emit-workflow: wrote .github/workflows/conjure-eval.yml"
  # Verification note (cross-cutting invariant: every emitted artifact ships with verification)
  echo "  Verify: add ANTHROPIC_API_KEY to GitHub repo secrets; open a PR touching .claude/ to trigger the eval gate"
  # Manual enforcement obligation (EVAL-03 enforcement-not-disposition)
  echo "  Manual-UAT: break a hook binary and confirm the eval suite FAILS (requires live promptfoo + ANTHROPIC_API_KEY)"
}

# ──────────────────────────────────────────────────────────────────────────────
# Main dispatch
# Reads CONJURE_EVAL_CMD env var (set by cli/conjure) OR falls back to $1 for
# direct invocation (test harness passes subcmd as first positional arg).
# ──────────────────────────────────────────────────────────────────────────────
CMD="${CONJURE_EVAL_CMD:-}"
if [ -z "$CMD" ]; then
  CMD="${1:-}"
  [ $# -gt 0 ] && shift
fi
TARGET="${1:-$(pwd)}"

case "$CMD" in
  init)            cmd_eval_init "$TARGET" ;;
  run)             cmd_eval_run "$TARGET" ;;
  --emit-workflow) cmd_eval_emit_workflow "$TARGET" ;;
  *)               echo "Usage: conjure eval init|run|--emit-workflow [target]" >&2; exit 2 ;;
esac
